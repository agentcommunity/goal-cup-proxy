#[cfg(test)]
mod pin_table_tests {
    use super::*;

    /// Production trust is exactly the generated tables, read the way the protocol reads them.
    #[test]
    fn the_current_build_tables_are_the_generated_ones() {
        let build = PinTables::CURRENT_BUILD;
        assert_eq!(build.manifests(), CONNECTOR_MANIFEST_SHA256S);
        assert_eq!(build.directories(), CONNECTOR_DIR_SHA256S);
        for (id, sha) in CONNECTOR_MANIFEST_SHA256S {
            assert_eq!(pinned_manifest_sha256(id), Some(*sha));
            let resolved = ManifestPinning::resolve(id, sha, false);
            assert_eq!(resolved.state, ManifestPin::Pinned);
            assert_eq!(resolved.tables, build);
        }
        for (id, sha) in CONNECTOR_DIR_SHA256S {
            for spelling in [sha.to_string(), sha.to_ascii_uppercase()] {
                assert!(build.directory_is_pinned(id, &spelling));
                assert!(goalcup_protocol::pins::connector_dir_is_pinned(
                    id, &spelling
                ));
            }
            let other = "0".repeat(64);
            assert!(!build.directory_is_pinned(id, &other));
            assert!(!goalcup_protocol::pins::connector_dir_is_pinned(id, &other));
        }
        assert!(!build.directory_is_pinned("no-such-cli", CONNECTOR_DIR_SHA256S[0].1));
        assert_eq!(build.manifest_sha256("no-such-cli"), None);
        assert_eq!(ManifestPinning::default().tables, build);
    }
}

#[cfg(test)]
mod key_tests {
    use super::*;
    use ed25519_dalek::SigningKey;

    /// The placeholder in `SERVER_PUBLIC_KEYS` is exactly the key the test suite signs
    /// with. Re-derived rather than re-typed, so the constant and the tests cannot drift.
    #[test]
    fn the_placeholder_key_is_the_one_the_tests_sign_with() {
        let signer = SigningKey::from_bytes(&[5u8; 32]);
        assert_eq!(
            SERVER_PUBLIC_KEYS[0],
            hex::encode(signer.verifying_key().to_bytes())
        );
    }

    /// The descriptor validator accepts uppercase hex, so the allowlist has to as well.
    #[test]
    fn an_allowlisted_key_in_uppercase_is_still_pinned() {
        let shouted = SERVER_PUBLIC_KEYS[0].to_ascii_uppercase();
        let options = VerifyOptions::default();
        let (key, source) = resolve_server_key(Some(&shouted), &options);
        assert_eq!(key, Some(shouted.as_str()));
        assert_eq!(source, KeySource::Pinned);
    }

    #[test]
    fn an_allowlisted_descriptor_key_is_pinned() {
        let options = VerifyOptions {
            allow_descriptor_key: false,
            ..VerifyOptions::default()
        };
        let (key, source) = resolve_server_key(Some(SERVER_PUBLIC_KEYS[0]), &options);
        assert_eq!(key, Some(SERVER_PUBLIC_KEYS[0]));
        assert_eq!(source, KeySource::Pinned);
    }

    /// A key the participant wrote into their own descriptor is not an anchor, and the
    /// default run ignores it.
    #[test]
    fn an_unknown_descriptor_key_is_ignored_by_default() {
        let stranger = "a".repeat(64);
        let options = VerifyOptions::default();
        let (key, source) = resolve_server_key(Some(&stranger), &options);
        assert_eq!(key, None);
        assert_eq!(source, KeySource::None);
    }

    #[test]
    fn the_dev_flag_accepts_an_unknown_key_and_says_so() {
        let stranger = "a".repeat(64);
        let options = VerifyOptions {
            allow_descriptor_key: true,
            ..VerifyOptions::default()
        };
        let (key, source) = resolve_server_key(Some(&stranger), &options);
        assert_eq!(key, Some(stranger.as_str()));
        assert_eq!(source, KeySource::Descriptor);
    }

    /// The development signer is honoured for this run and for nothing else: the key
    /// never enters `SERVER_PUBLIC_KEYS`, and the verdict says the trust was borrowed.
    #[test]
    fn a_supplied_key_is_accepted_for_this_run_and_named_as_supplied() {
        let dev = "b".repeat(64);
        let options = VerifyOptions {
            extra_server_keys: vec![dev.clone()],
            ..VerifyOptions::default()
        };
        let (key, source) = resolve_server_key(Some(&dev), &options);
        assert_eq!(key, Some(dev.as_str()));
        assert_eq!(source, KeySource::Supplied);

        // Hex case is not meaningful here either.
        let shouted = dev.to_ascii_uppercase();
        let (key, source) = resolve_server_key(Some(&shouted), &options);
        assert_eq!(key, Some(shouted.as_str()));
        assert_eq!(source, KeySource::Supplied);

        // A key that is on neither list is still no key.
        let stranger = "c".repeat(64);
        let (key, source) = resolve_server_key(Some(&stranger), &options);
        assert_eq!(key, None);
        assert_eq!(source, KeySource::None);

        // And supplying one does not put it in the pinned constant.
        assert!(!SERVER_PUBLIC_KEYS.contains(&dev.as_str()));
        assert_eq!(SERVER_PUBLIC_KEYS.len(), 1);
    }

    /// The pinned allowlist wins over the supplied list, so passing the real anchor with
    /// `--dev-key` cannot downgrade a genuinely pinned run to a borrowed one.
    #[test]
    fn a_pinned_key_stays_pinned_even_when_it_is_also_supplied() {
        let options = VerifyOptions {
            extra_server_keys: vec![SERVER_PUBLIC_KEYS[0].to_string()],
            ..VerifyOptions::default()
        };
        let (key, source) = resolve_server_key(Some(SERVER_PUBLIC_KEYS[0]), &options);
        assert_eq!(key, Some(SERVER_PUBLIC_KEYS[0]));
        assert_eq!(source, KeySource::Pinned);
    }

    /// `VerifyOptions::default()` supplies nothing, so `verify_trace` is unchanged.
    #[test]
    fn the_default_run_supplies_no_key_at_all() {
        assert!(VerifyOptions::default().extra_server_keys.is_empty());
        let stranger = "d".repeat(64);
        let options = VerifyOptions::default();
        let (key, source) = resolve_server_key(Some(&stranger), &options);
        assert_eq!(key, None);
        assert_eq!(source, KeySource::None);
    }

    #[test]
    fn no_descriptor_key_is_none_under_either_option() {
        for allow_descriptor_key in [false, true] {
            let options = VerifyOptions {
                allow_descriptor_key,
                ..VerifyOptions::default()
            };
            let (key, source) = resolve_server_key(None, &options);
            assert_eq!(key, None);
            assert_eq!(source, KeySource::None);
        }
    }
}

#[derive(Debug, thiserror::Error)]
pub enum VerifierError {
    #[error("verdict json: {0}")]
    VerdictJson(serde_json::Error),
    /// An attacker-controlled evidence document exceeded its declared verifier bound.
    #[error("evidence {path} exceeds the {limit}-byte verifier limit")]
    EvidenceTooLarge { path: String, limit: u64 },
    /// Retaining another valid JSONL record would exceed the whole-run evidence budget.
    #[error(
        "evidence retention at {path} would reach {bytes} bytes/{records} records, over the \
         verifier limits of {byte_limit} bytes/{record_limit} records"
    )]
    AggregateEvidenceTooLarge {
        path: String,
        bytes: u64,
        records: u64,
        byte_limit: u64,
        record_limit: u64,
    },
    #[error("trace declares {found} raw bodies, over the verifier limit of {limit}")]
    RawBodyCountTooLarge { found: usize, limit: usize },
    #[error("trace declares duplicate raw {field} `{value}`")]
    DuplicateRaw { field: &'static str, value: String },
    #[error("io {path}: {source}")]
    Io {
        path: String,
        #[source]
        source: std::io::Error,
    },
    #[error("json {path} line {line}: {source}")]
    Json {
        path: String,
        line: usize,
        #[source]
        source: serde_json::Error,
    },
    #[error("toml {path}: {source}")]
    Toml {
        path: String,
        #[source]
        source: toml::de::Error,
    },
    #[error("protocol: {0}")]
    Protocol(#[from] goalcup_protocol::ProtocolError),
    #[error("no parser for connector family {0}")]
    UnknownParserFamily(String),
    /// The descriptor's `connector` and the manifest it points at name different
    /// connectors. Both fields are written by the participant, and the pair decides which
    /// parser runs and which human rule judges it; a trace that disagrees with itself
    /// about that is not verifiable.
    #[error(
        "connector mismatch: trace.toml declares connector `{descriptor}` but the manifest \
         at {path} declares id `{manifest}`"
    )]
    ConnectorMismatch {
        descriptor: String,
        manifest: String,
        path: String,
    },
    /// A descriptor names a chain and declares evidence outside it.
    ///
    /// There is no honest way to read such a trace. The chain is the evidence: every
    /// record in it is a link the daemon stamped and a server may have acknowledged. A
    /// store file beside it is a claim with nothing behind it — no link covers a byte of
    /// it — so merging the two lets a participant hand over an acknowledged chain and,
    /// next to it, a file holding whatever they like, which every check downstream reads
    /// as leg-1 evidence. Refusing is the only answer that does not pick one of the two
    /// on no grounds.
    ///
    /// A legacy M0 descriptor declares stores and no chain, and is unaffected.
    #[error(
        "trace.toml declares a chain and {leg1} [[leg1]] store(s){}: a chain trace declares \
         no stores — everything both legs hold is in the chain, and a file beside it is \
         evidence nothing links to",
        if *.leg2 { " and a [leg2] table" } else { "" }
    )]
    ChainDeclaresStores { leg1: usize, leg2: bool },
    #[error("trace: {0}")]
    Trace(String),
}

impl From<budget::RetentionLimit> for VerifierError {
    fn from(limit: budget::RetentionLimit) -> Self {
        Self::AggregateEvidenceTooLarge {
            path: limit.path,
            bytes: limit.bytes,
            records: limit.records,
            byte_limit: limit.byte_limit,
            record_limit: limit.record_limit,
        }
    }
}
