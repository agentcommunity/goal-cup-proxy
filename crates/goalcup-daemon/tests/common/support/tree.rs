//! The process-group escape helper.
//!
//! The measured shape has the native
//! `codex` binary as an interior node — a child of the registered root, itself the parent
//! of every process the session actually spawns, each of which leaves `codex`'s process
//! group the instant it forks. No `/bin/sh` primitive builds that shape: macOS ships no
//! `setsid(1)` at all, and the POSIX substitute, `set -m`, is vacuous on Linux because
//! `/bin/sh` there is dash, which turns job control off the moment it detects no
//! controlling tty. The one primitive that reliably leaves a process group on both platforms is
//! `std::os::unix::process::CommandExt::process_group`, and that is Rust, not shell.
//!
//! So the escape happens by re-entering this same compiled test binary under a second
//! identity. `hardlink_codex_helper` hard-links `std::env::current_exe()` (no copy — the
//! link lives under `$CARGO_TARGET_TMPDIR`, guaranteed to share a filesystem with the
//! compiled binary because that directory is `<target-dir>/tmp`) to a file literally named
//! `codex`. A fixture script then runs that hard link as an ordinary child process, with
//! `GOALCUP_FIXTURE_ROLE` set in its environment. `goalcup_protocol::process::snapshot`
//! keeps only the last `/`-component of whatever `ps` prints for `comm`
//! (`crates/goalcup-protocol/src/process.rs`'s `snapshot`), so it does not matter whether
//! the fixture invokes the link by its full path or a bare name on `PATH` — either way the
//! row this process leaves in a `ps` snapshot reads `comm == "codex"`, exactly the identity
//! `kill.native_binary` pins for the real connector.
//!
//! ## Why the role dispatch cannot be an ordinary `#[test]`
//!
//! The re-exec'd process is, at the bytes level, the exact same test binary that every
//! other `#[test]` in `process_kill.rs` lives in. Its `fn main` is libtest's, generated by
//! the `--test` harness, and — with no test-selecting argv, which this module deliberately
//! never constructs — an unfiltered libtest `main` runs the entire suite, recursively, as a
//! child of whatever fixture spawned it. There is no supported way to intercept that from
//! inside an `#[test]` function: by the time any test body runs, libtest has already parsed
//! argv and chosen what to run.
//!
//! What runs before all of that, on every Unix `cc`-linked binary, is a process's array of
//! link-time constructors — the same mechanism the `ctor` crate wraps, and hand-written here
//! because this workspace's `--offline` vendor set does not carry that crate. A `#[used]`
//! static placed in `.init_array` (Linux/ELF) or `__DATA,__mod_init_func` (macOS/Mach-O) is
//! called by the OS loader strictly before `main`, so it runs before libtest ever reads
//! argv. It reads `GOALCUP_FIXTURE_ROLE` from the environment rather than from
//! `std::env::args()` deliberately: Rust's own argv capture is not guaranteed to have run
//! yet at this point (`std::env::args()` is unsafe to rely on pre-`main` on at least Linux),
//! while the process environment (`environ`) is populated by `exec` itself and is safe to
//! read at any point afterward. When the role fires it calls `std::process::exit` directly
//! — the ordinary `fn main` below, and the rest of the test suite, is never reached.
//!
//! A second role, `run_member_forks_after_root_role`, reuses the same re-exec mechanism for
//! an unrelated problem: the adoption-window fixture's shell-based delay is itself a
//! forked, signallable process, which put that fixture on the same race this module exists
//! to remove for process groups. See that function's own doc.
use std::env;
use std::fs;
use std::path::PathBuf;
use std::process::{Command, Stdio};

/// Set by a fixture script (or by Rust code building one directly) to select a role. Read
/// only by the constructor below; unset, this process is an ordinary test binary.
pub const ROLE_ENV: &str = "GOALCUP_FIXTURE_ROLE";
/// Where the role writes the pids it spawned, one per line. Required by every role.
pub const PIDFILE_ENV: &str = "GOALCUP_FIXTURE_PIDFILE";
/// How many children the `native-interior` role spawns. Optional; defaults to 3, the
/// measured shape's own count, but `wrapper-setpgid-grandchild.sh` reuses the same role
/// with exactly one so it needs no second helper binary.
pub const CHILDREN_ENV: &str = "GOALCUP_FIXTURE_CHILDREN";

/// Spawn N children, each in a process group of its own (`Command::process_group(0)`),
/// write their pids to `PIDFILE_ENV`, and wait for all of them. That is the whole shape a
/// `codex`-interior node needs, and — with `CHILDREN_ENV=1` — the whole shape a plain
/// escaped grandchild needs too.
const NATIVE_INTERIOR_ROLE: &str = "native-interior";

/// `wrapper-root-dies-first.sh`'s member, the adoption-window fixture's other half. Spawns
/// a `sleep 300` stand-in for the long-lived native session, blocks for `SIGTERM`, then
/// delays in-process (`std::thread::sleep`, no forked helper) before forking a detached
/// orphan and naming it to `PIDFILE_ENV`. See that function's own doc for why the delay
/// being in-process is the whole point.
const MEMBER_FORKS_AFTER_ROOT_ROLE: &str = "member-forks-after-root";

// The constructor entries. Two sections because the two platforms this crate supports
// (`crates/goalcup-daemon/tests/full/main.rs` gates `process_kill` on `cfg(unix)`)
// name their init-array sections differently; everywhere else this static is simply absent,
// and the role can never fire, which is fine because nothing on those targets ever sets
// `GOALCUP_FIXTURE_ROLE`.
#[cfg(target_os = "linux")]
#[used]
#[unsafe(link_section = ".init_array")]
static INIT_ARRAY: extern "C" fn() = fixture_role_ctor;

#[cfg(target_os = "macos")]
#[used]
#[unsafe(link_section = "__DATA,__mod_init_func")]
static INIT_ARRAY: extern "C" fn() = fixture_role_ctor;

#[cfg(any(target_os = "linux", target_os = "macos"))]
extern "C" fn fixture_role_ctor() {
    // `environ`-backed and safe this early; `std::env::args()` is deliberately never
    // touched here — see the module doc.
    let Ok(role) = env::var(ROLE_ENV) else {
        return;
    };
    match role.as_str() {
        NATIVE_INTERIOR_ROLE => run_native_interior_role(),
        MEMBER_FORKS_AFTER_ROOT_ROLE => run_member_forks_after_root_role(),
        // An unrecognised role is a fixture bug, not a reason to fall through into running
        // this binary's entire test suite as somebody else's child.
        other => {
            eprintln!("goalcup fixture: unknown {ROLE_ENV}={other:?}");
            std::process::exit(70);
        }
    }
}

/// Spawn N `sleep 300`s, each detached into its own process group, name them to the
/// pidfile, and wait for all of them. Never returns.
#[cfg(any(target_os = "linux", target_os = "macos"))]
fn run_native_interior_role() -> ! {
    let pidfile = env::var(PIDFILE_ENV)
        .unwrap_or_else(|_| panic!("goalcup fixture: {PIDFILE_ENV} must be set"));
    let n: usize = env::var(CHILDREN_ENV)
        .ok()
        .and_then(|s| s.parse().ok())
        .unwrap_or(3);

    let mut children = Vec::with_capacity(n);
    let mut pids = Vec::with_capacity(n);
    for _ in 0..n {
        // `std::os::unix::process::CommandExt::process_group(0)` is the one primitive this
        // whole module exists to reach: it makes the child its own process-group leader,
        // which neither `/bin/sh` on macOS (no `setsid(1)`) nor dash on Linux (`set -m` is
        // vacuous without a tty) can do.
        use std::os::unix::process::CommandExt;
        let mut cmd = Command::new("sleep");
        cmd.arg("300");
        cmd.process_group(0);
        cmd.stdin(Stdio::null());
        cmd.stdout(Stdio::null());
        cmd.stderr(Stdio::null());
        let child = cmd
            .spawn()
            .unwrap_or_else(|e| panic!("goalcup fixture: spawn a native-interior child: {e}"));
        pids.push(child.id());
        children.push(child);
    }

    let body = pids
        .iter()
        .map(u32::to_string)
        .collect::<Vec<_>>()
        .join("\n");
    fs::write(&pidfile, body).unwrap_or_else(|e| panic!("goalcup fixture: write {pidfile}: {e}"));

    for mut child in children {
        let _ = child.wait();
    }
    std::process::exit(0);
}

/// The write end of the self-pipe the `SIGTERM` handler below wakes. `-1` until the role
/// installs it; a signal handler may run on any thread and touches nothing but this.
#[cfg(any(target_os = "linux", target_os = "macos"))]
static MEMBER_TERM_PIPE_WRITE: std::sync::atomic::AtomicI32 = std::sync::atomic::AtomicI32::new(-1);

/// Async-signal-safe: `write(2)` is on the POSIX signal-safe list, `AtomicI32::load` is
/// lock-free. Nothing else may run in a signal handler — no allocation, no `println!`, no
/// mutex — which is the whole reason this exists instead of, say, a channel `Sender`.
#[cfg(any(target_os = "linux", target_os = "macos"))]
extern "C" fn member_term_handler(_signum: libc::c_int) {
    let fd = MEMBER_TERM_PIPE_WRITE.load(std::sync::atomic::Ordering::SeqCst);
    if fd >= 0 {
        let byte: u8 = 1;
        unsafe {
            libc::write(fd, (&byte as *const u8).cast(), 1);
        }
    }
}

/// The adoption-window fixture's member. Its `SIGTERM` handler delays in-process, with no
/// forked helper: a forked delay helper is itself a fresh descendant this daemon's own
/// newcomer-adoption can discover and signal mid-delay, which puts the delay on the same
/// race as the shape the fixture exists to prove absent.
///
/// No fork happens during the delay at all: `std::thread::sleep` blocks this process's own
/// thread via a clock syscall, so there is no new pid for newcomer-adoption to ever see
/// mid-delay, and the race this function exists to remove cannot recur by construction —
/// not "made less likely", removed.
#[cfg(any(target_os = "linux", target_os = "macos"))]
fn run_member_forks_after_root_role() -> ! {
    use std::sync::atomic::Ordering;

    let pidfile = env::var(PIDFILE_ENV)
        .unwrap_or_else(|_| panic!("goalcup fixture: {PIDFILE_ENV} must be set"));

    // The stand-in for the long-lived native session process the measured shape hides —
    // present from the start, exactly like the shell member's own first line, so the
    // fixture's shape-proof (three processes: root, this member, this child) holds before
    // any signal is ever sent.
    let _native_standin = Command::new("sleep")
        .arg("300")
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .spawn()
        .unwrap_or_else(|e| panic!("goalcup fixture: spawn the native stand-in: {e}"));

    // The self-pipe: `write(2)` from the handler is what a signal handler may safely do;
    // blocking on the read end is this thread's only job until `SIGTERM` arrives. Installed
    // before `signal(2)` so there is no window where a delivered signal has nowhere to
    // write — a pipe buffers, so a `SIGTERM` that lands between `signal(2)` and the `read`
    // below is still there waiting when the `read` starts.
    let mut fds = [0i32; 2];
    if unsafe { libc::pipe(fds.as_mut_ptr()) } != 0 {
        panic!("goalcup fixture: pipe(2) failed");
    }
    MEMBER_TERM_PIPE_WRITE.store(fds[1], Ordering::SeqCst);
    let installed = unsafe {
        libc::signal(
            libc::SIGTERM,
            member_term_handler as *const () as libc::sighandler_t,
        )
    };
    if installed == libc::SIG_ERR {
        panic!("goalcup fixture: signal(SIGTERM) failed");
    }

    // Blocks until the handler above writes a byte — i.e. until `SIGTERM` is delivered.
    // Independent of `_native_standin`'s own lifecycle by construction: unlike the shell
    // version's `sleep 300 & ; wait`, nothing here waits on that child, so the daemon
    // signalling and killing it first (which it does, as an ordinary discovered
    // descendant) cannot race this member's own termination handling.
    let mut byte = [0u8; 1];
    unsafe {
        libc::read(fds[0], byte.as_mut_ptr().cast(), 1);
    }

    // The delay itself: ~400ms, comfortably after root's own ~120ms delayed exit
    // (`wrapper-root-dies-first.sh`), so the daemon's authority over root
    // (`Anchor::Rooted`) is already closed by the time the orphan below exists. In-process,
    // so nothing here is a descendant newcomer-adoption could ever see.
    std::thread::sleep(std::time::Duration::from_millis(400));

    // The detached grandchild directly (no intermediate shell subshell, which would
    // reparent it to init immediately and test the pre-existing-orphan
    // case instead of the post-root-death adoption window this fixture exists for).
    let orphan = Command::new("sleep")
        .arg("300")
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .spawn()
        .unwrap_or_else(|e| panic!("goalcup fixture: spawn the orphan: {e}"));
    fs::write(&pidfile, orphan.id().to_string())
        .unwrap_or_else(|e| panic!("goalcup fixture: write {pidfile}: {e}"));
    // Deliberately not `orphan.wait()`ed: this member exits immediately afterward (matching
    // the shell member's own `exit 0` right after writing the pidfile), and the orphan is
    // inherited by the nearest surviving reaper the moment it does.
    std::process::exit(0);
}

/// Hard-link this compiled test binary to `$CARGO_TARGET_TMPDIR/<test_name>/codex`, so a
/// fixture script can run it as a child process named `codex` (see the module doc for why
/// the exact name reaches `ProcInfo::comm`).
///
/// `test_name` only needs to be distinct per caller in the same test session — it becomes a
/// directory name, not a synchronisation key — so each new fixture test in this file picks
/// its own literal.
pub fn hardlink_codex_helper(test_name: &str) -> PathBuf {
    let base = PathBuf::from(env!("CARGO_TARGET_TMPDIR")).join(test_name);
    fs::create_dir_all(&base)
        .unwrap_or_else(|e| panic!("goalcup fixture: create {}: {e}", base.display()));
    let dest = base.join("codex");
    // A stale link from an earlier run of this same binary: `hard_link` refuses to
    // overwrite, and the fixture wants this session's own binary under it regardless.
    let _ = fs::remove_file(&dest);
    let exe = env::current_exe().expect("goalcup fixture: current_exe");
    fs::hard_link(&exe, &dest).unwrap_or_else(|e| {
        panic!(
            "goalcup fixture: hard_link {} -> {}: {e}",
            exe.display(),
            dest.display()
        )
    });
    dest
}
